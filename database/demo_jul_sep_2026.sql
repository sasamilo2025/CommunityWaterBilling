-- Step 2: Assign meters 3,2,2,1,1,1. All installed before opening reading.
INSERT INTO meters (meter_serial, customer_id, location, status, installed_at)
SELECT x.meter_serial, c.customer_id, x.location, 'ACTIVE', '2026-06-15'
FROM (
    SELECT '88000001' AS meter_serial, 'DEM01' AS customer_no, 'Location A - meter 1' AS location
    UNION ALL SELECT '88000002', 'DEM01', 'Location A - meter 2'
    UNION ALL SELECT '88000003', 'DEM01', 'Location A - meter 3'
    UNION ALL SELECT '88000004', 'DEM02', 'Location B - meter 1'
    UNION ALL SELECT '88000005', 'DEM02', 'Location B - meter 2'
    UNION ALL SELECT '88000006', 'DEM03', 'Location C - meter 1'
    UNION ALL SELECT '88000007', 'DEM03', 'Location C - meter 2'
    UNION ALL SELECT '88000008', 'DEM04', 'Location D - meter 1'
    UNION ALL SELECT '88000009', 'DEM05', 'Location E - meter 1'
    UNION ALL SELECT '88000010', 'DEM06', 'Location A - meter 1'
) AS x
JOIN customers AS c ON c.customer_no = x.customer_no;

-- Step 3: 10 opening readings at June month end (not billable).
INSERT INTO meter_readings (meter_serial, billing_month, reading_date, reading_type, reading_value)
SELECT meter_serial, '2026-06-01', '2026-06-30', 'INITIAL',
       100 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED) * 10
FROM meters WHERE meter_serial BETWEEN '88000001' AND '88000010';

-- Step 4: 10 July readings. July consumption per meter = 10 + index m3.
INSERT INTO meter_readings (meter_serial, billing_month, reading_date, reading_type, reading_value)
SELECT meter_serial, '2026-07-01', '2026-07-31', 'MONTHLY',
       100 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED) * 10
           + 10 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED)
FROM meters WHERE meter_serial BETWEEN '88000001' AND '88000010';

-- Step 5: 10 August readings. August consumption = 15 + index m3.
INSERT INTO meter_readings (meter_serial, billing_month, reading_date, reading_type, reading_value)
