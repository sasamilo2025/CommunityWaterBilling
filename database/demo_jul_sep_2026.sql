-- Step 6: 10 September readings. September consumption = 20 + index m3.
INSERT INTO meter_readings (meter_serial, billing_month, reading_date, reading_type, reading_value)
SELECT meter_serial, '2026-09-01', '2026-09-30', 'MONTHLY',
       100 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED) * 10
           + 10 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED)
           + 15 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED)
           + 20 + CAST(RIGHT(meter_serial, 2) AS UNSIGNED)
FROM meters WHERE meter_serial BETWEEN '88000001' AND '88000010';

-- Step 7: One invoice per MONTHLY reading (30 total).
-- Invoice numbers 260701–260710, 260801–260810, 260901–260910.
-- Consumption, total_amount and payment_due_date are generated by MySQL.
INSERT INTO bills
    (invoice_number, reading_id, previous_reading, current_reading,
     rate_per_m3, invoice_date, status)
SELECT
    CONCAT(DATE_FORMAT(r.billing_month, '%y%m'), RIGHT(r.meter_serial, 2)),
    r.reading_id,
    prev.reading_value,
    r.reading_value,
    0.50,
    DATE_ADD(LAST_DAY(r.billing_month), INTERVAL 1 DAY),
    'UNPAID'
FROM meter_readings AS r
JOIN meter_readings AS prev
  ON prev.meter_serial = r.meter_serial
 AND prev.billing_month = DATE_SUB(r.billing_month, INTERVAL 1 MONTH)
 AND prev.reading_type = CASE
       WHEN r.billing_month = '2026-07-01' THEN 'INITIAL'
       ELSE 'MONTHLY'
     END
WHERE r.meter_serial BETWEEN '88000001' AND '88000010'
  AND r.reading_type = 'MONTHLY'
  AND r.billing_month BETWEEN '2026-07-01' AND '2026-09-01';

-- ==================================================
-- STEP 8: VERIFY DEMONSTRATION RECORDS
-- ==================================================
--
-- IMPORTANT:
-- The transaction remains OPEN.
--
-- Review these counts before issuing COMMIT.
--
-- Expected:
-- Customers = 6
-- Meters    = 10
-- Readings  = 40
-- Invoices  = 30
--
-- If anything is incorrect, execute ROLLBACK.
-- ==================================================

SELECT
    (SELECT COUNT(*)
     FROM customers
     WHERE customer_no BETWEEN 'DEM01' AND 'DEM06')
        AS demo_customers,

    (SELECT COUNT(*)
     FROM meters
     WHERE meter_serial BETWEEN '88000001' AND '88000010')
        AS demo_meters,

    (SELECT COUNT(*)
     FROM meter_readings
     WHERE meter_serial BETWEEN '88000001' AND '88000010')
        AS demo_readings,

    (SELECT COUNT(*)
     FROM bills
     WHERE invoice_number REGEXP '^260[789][0-9]{2}$')
        AS demo_invoices;

-- ==================================================
-- NO COMMIT HERE!
-- Wait for ADMIN confirmation.
-- ==================================================
-- Step 9: Read-only verification after successful commit.
SELECT 'Demo customers' AS item, COUNT(*) AS total FROM customers WHERE customer_no BETWEEN 'DEM01' AND 'DEM06'
UNION ALL SELECT 'Demo meters', COUNT(*) FROM meters WHERE meter_serial BETWEEN '88000001' AND '88000010'
UNION ALL SELECT 'Demo readings', COUNT(*) FROM meter_readings WHERE meter_serial BETWEEN '88000001' AND '88000010'
UNION ALL SELECT 'Demo invoices', COUNT(*) FROM bills WHERE invoice_number REGEXP '^260[789][0-9]{2}$';

SELECT DATE_FORMAT(r.billing_month, '%Y-%m') AS report_month,
       COUNT(*) AS invoices, SUM(b.consumption_m3) AS total_m3,
       SUM(b.total_amount) AS total_cost
FROM bills AS b
JOIN meter_readings AS r ON r.reading_id = b.reading_id
WHERE r.meter_serial BETWEEN '88000001' AND '88000010'
  AND r.billing_month BETWEEN '2026-07-01' AND '2026-09-01'
GROUP BY r.billing_month ORDER BY r.billing_month;
